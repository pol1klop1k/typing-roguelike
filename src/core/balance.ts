export type Balance = typeof BALANCE

/**
 * Значения по умолчанию, снятые ДО применения правок админки.
 *
 * Нужны двум разным читателям. Админке - чтобы показать, от чего игрок
 * отклонился. Тестам - чтобы проверять ЗАМЫСЕЛ, а не текущую настройку:
 * например, что лестница редкостей убывает. Наладка на то и наладка, чтобы
 * в ней можно было поставить заведомо нелепое число и посмотреть, что будет;
 * набор тестов от этого падать не должен.
 */
export const BALANCE_DEFAULTS: Balance = structuredClone(BALANCE) as Balance

/** Ключи баланса, за которыми стоит одно число. Только их правит админка. */
export type BalanceNumberKey = {
  [K in keyof Balance]: Balance[K] extends number ? K : never
}[keyof Balance]

/**
 * Правки баланса: отдельные числа плюс обе таблицы редкостей.
 *
 * Таблицы описаны через Record<Rarity, number>, а не через тип самого
 * BALANCE: из-за `as const` там стоят литеральные типы вроде 100, и любая
 * другая цифра в них не влезает.
 */
export interface BalanceOverrides {
  readonly numbers?: Partial<Record<BalanceNumberKey, number>>
  readonly rarityWeights?: Partial<Record<Rarity, number>>
  readonly rarityBasePrice?: Partial<Record<Rarity, number>>
}

/**
 * Накладывает правки админки на значения по умолчанию.
 *
 * Функция живёт в ядре, а файл с правками - в content, и направление
 * зависимостей от этого не страдает: ядро предоставляет шов, а кто в него
 * что подставит, ядру знать незачем.
 *
 * Вызывать нужно ДО того, как значения кто-нибудь прочитает. За это отвечает
 * content/tuning.ts: он применяет правки в момент загрузки модуля, а все,
 * кому нужны числа, импортируют его раньше, чем считают.
 */
export function overrideBalance(patch: BalanceOverrides): void {
  // Единственное место, где BALANCE меняется. Приведение типа здесь
  // осознанное: снаружи объект обязан оставаться readonly.
  const target = BALANCE as unknown as Record<string, unknown>

  for (const [key, value] of Object.entries(patch.numbers ?? {})) {
    if (typeof value === 'number' && Number.isFinite(value) && key in BALANCE) {
      target[key] = value
    }
  }

  Object.assign(BALANCE.rarityWeights as Record<Rarity, number>, patch.rarityWeights ?? {})
  Object.assign(BALANCE.rarityBasePrice as Record<Rarity, number>, patch.rarityBasePrice ?? {})
}
